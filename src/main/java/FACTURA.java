    private void jButtonELIMINARActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonELIMINARActionPerformed
        // TODO add your handling code here:String texto = listaProductos.toString();

    String texto = listaProductos.toString();  // ← ahora sí existe

    int ultimaLinea = texto.lastIndexOf("\n");

    if (ultimaLinea != -1) {
        listaProductos = new StringBuilder(texto.substring(0, ultimaLinea));
    }

    jTextArea1.setText(listaProductos.toString());

    }//GEN-LAST:event_jButtonELIMINARActionPerformed

    private void jButtonAGREGARActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAGREGARActionPerformed
        // TODO add your handling code here:
            String nombre = jTextFieldNOMBRE.getText();
    String nit = jTextFieldNIT.getText();

    // Detectar cuál producto se está llenando
    if (!jTextFieldPRECIO1.getText().isEmpty() && !jTextFieldCANTIDAD1.getText().isEmpty()) {
        String prod1 = (String) jComboBoxPRODUCTO1.getSelectedItem();
        double precio1 = parseDoubleSafe(jTextFieldPRECIO1.getText());
        int cant1 = parseIntSafe(jTextFieldCANTIDAD1.getText());
        double total1 = precio1 * cant1;

        listaProductos.append("Producto 1: ").append(prod1)
                .append(" | Precio: ").append(precio1)
                .append(" | Cantidad: ").append(cant1)
                .append(" | Subtotal: ").append(total1)
                .append("\n");
    }

    if (!jTextFieldPRECIO2.getText().isEmpty() && !jTextFieldCANTIDAD2.getText().isEmpty()) {
        String prod2 = (String) jComboBoxPRODUCTO2.getSelectedItem();
        double precio2 = parseDoubleSafe(jTextFieldPRECIO2.getText());
        int cant2 = parseIntSafe(jTextFieldCANTIDAD2.getText());
        double total2 = precio2 * cant2;

        listaProductos.append("Producto 2: ").append(prod2)
                .append(" | Precio: ").append(precio2)
                .append(" | Cantidad: ").append(cant2)
                .append(" | Subtotal: ").append(total2)
                .append("\n");
    }

    if (!jTextFieldNOMBRE3.getText().isEmpty() && !jTextFieldCANTIDAD3.getText().isEmpty()) {
        String prod3 = (String) jComboBoxPRODUCTO3.getSelectedItem();
        double precio3 = parseDoubleSafe(jTextFieldNOMBRE3.getText());
        int cant3 = parseIntSafe(jTextFieldCANTIDAD3.getText());
        double total3 = precio3 * cant3;

        listaProductos.append("Producto 3: ").append(prod3)
                .append(" | Precio: ").append(precio3)
                .append(" | Cantidad: ").append(cant3)
                .append(" | Subtotal: ").append(total3)
                .append("\n");
    }

    jTextArea1.setText(listaProductos.toString());

    }//GEN-LAST:event_jButtonAGREGARActionPerformed

