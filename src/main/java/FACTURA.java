    private void jButtonIMPRIMIRActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonIMPRIMIRActionPerformed
        // TODO add your handling code here:
                                               
    // Datos generales
    String nombre = jTextFieldNOMBRE.getText();
    String nit = jTextFieldNIT.getText();

    // Producto 1
    String prod1 = (String) jComboBoxPRODUCTO1.getSelectedItem();
    double precio1 = parseDoubleSafe(jTextFieldPRECIO1.getText());
    int cant1 = parseIntSafe(jTextFieldCANTIDAD1.getText());
    double total1 = precio1 * cant1;

    // Producto 2
    String prod2 = (String) jComboBoxPRODUCTO2.getSelectedItem();
    double precio2 = parseDoubleSafe(jTextFieldPRECIO2.getText());
    int cant2 = parseIntSafe(jTextFieldCANTIDAD2.getText());
    double total2 = precio2 * cant2;

    // Producto 3
    String prod3 = (String) jComboBoxPRODUCTO3.getSelectedItem();
    double precio3 = parseDoubleSafe(jTextFieldNOMBRE3.getText()); // ESTE ES EL PRECIO 3
    int cant3 = parseIntSafe(jTextFieldCANTIDAD3.getText());
    double total3 = precio3 * cant3;

    // Total general
    double totalGeneral = total1 + total2 + total3;

    // Mostrar factura
    jTextArea1.setText(
        """
        ********** FACTURA **********
        Nombre: """ + nombre + "\n" +
        "NIT: " + nit + "\n\n" +
        "Producto 1: " + prod1 + "\n" +
        "Precio: " + precio1 + "   Cantidad: " + cant1 + "\n" +
        "Subtotal: " + total1 + "\n\n" +
        "Producto 2: " + prod2 + "\n" +
        "Precio: " + precio2 + "   Cantidad: " + cant2 + "\n" +
        "Subtotal: " + total2 + "\n\n" +
        "Producto 3: " + prod3 + "\n" +
        "Precio: " + precio3 + "   Cantidad: " + cant3 + "\n" +
        "Subtotal: " + total3 + "\n\n" +
        "TOTAL GENERAL: " + totalGeneral + "\n" +
        "******************************"
    );


    }//GEN-LAST:event_jButtonIMPRIMIRActionPerformed

